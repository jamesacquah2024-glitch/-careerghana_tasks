"""Renders outputs/alert_output.txt as an email-style image (outputs/triggered_alert_example.png)."""
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import FancyBboxPatch

msg = open("outputs/alert_output.txt").read().strip().split("\n")
fig, ax = plt.subplots(figsize=(9, 5)); ax.axis("off"); ax.set_xlim(0, 100); ax.set_ylim(0, 60)
ax.add_patch(FancyBboxPatch((1, 1), 98, 58, boxstyle="round,pad=0.3,rounding_size=2", fc="white", ec="#c8ccd2"))
ax.text(4, 54, "Subject: Budget alert: 3 categories flagged", fontsize=12, fontweight="bold", va="center")
ax.text(4, 49, "From: budget-alerts@example.com    To: finance-team@example.com", fontsize=8.5, color="#666", va="center")
ax.plot([3, 97], [46, 46], color="#ddd")
y = 41
for line in msg:
    if not line.strip():
        y -= 3; continue
    color = "#d9534f" if "[OVER" in line else "#c27a10" if "[WARN" in line else "#222"
    ax.text(4, y, line, fontsize=9.5, color=color, va="center")
    y -= 5.5
ax.text(4, 3, "Generated by budget_alert.py (dry-run output)", fontsize=7.5, color="#999")
plt.savefig("outputs/triggered_alert_example.png", dpi=150, bbox_inches="tight")
